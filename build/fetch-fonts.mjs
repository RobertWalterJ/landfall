// Landfall — fetch and self-host the two typefaces.
//
//   node build/fetch-fonts.mjs
//
// Self-hosted, not a CDN link: the app has to work offline on a phone, and an
// artifact sandbox will not load a third-party stylesheet anyway.
//
// The latin-ext and vietnamese subsets are not optional here. This corpus is
// full of Kraków, Ürümqi, Đắk Lắk, Île de la Gonâve and Curaçao — drop those
// subsets and a chunk of the world's place names render in a fallback face.

import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'app', 'fonts');
mkdirSync(OUT, { recursive: true });

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36';
const FAMILIES = [
  { css: 'Literata:opsz,wght@7..72,400;7..72,600;7..72,700', name: 'Literata', slug: 'literata' },
  { css: 'Archivo:wght@400;500;600;700', name: 'Archivo', slug: 'archivo' },
];
const WANT = new Set(['latin', 'latin-ext', 'vietnamese']);

const files = new Map();     // url -> filename
let css = '/* Self-hosted. Generated by build/fetch-fonts.mjs — do not edit. */\n';

for (const fam of FAMILIES) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${encodeURIComponent(fam.css).replace(/%3A/g, ':').replace(/%40/g, '@').replace(/%2C/g, ',').replace(/%3B/g, ';')}&display=swap`, { headers: { 'User-Agent': UA } });
  const text = await res.text();
  const blocks = text.split('/*').slice(1);
  for (const block of blocks) {
    const subset = block.slice(0, block.indexOf('*/')).trim();
    if (!WANT.has(subset)) continue;
    const url = block.match(/url\((https:[^)]+)\)/)?.[1];
    const weight = block.match(/font-weight:\s*([\d ]+);/)?.[1].trim();
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (!url) continue;
    let file = files.get(url);
    if (!file) {
      file = `${fam.slug}-${subset}-${weight.replace(/\s+/g, '-')}.woff2`;
      const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
      writeFileSync(join(OUT, file), buf);
      files.set(url, file);
      console.log(`  ${file.padEnd(34)} ${Math.round(buf.length / 1024)}KB`);
    }
    css += `@font-face{font-family:'${fam.name}';font-style:normal;font-weight:${weight.includes(' ') ? weight.replace(' ', ' ') : weight};font-display:swap;src:url(${file}) format('woff2');unicode-range:${range}}\n`;
  }
}
writeFileSync(join(OUT, 'fonts.css'), css);
console.log('wrote app/fonts/fonts.css —', files.size, 'files');
